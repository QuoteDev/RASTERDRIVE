const CHAR_WIDTH = 3; // 3 pixels wide per character
const CHAR_HEIGHT = 7;
const CHAR_SPACING = 1; // 1 pixel between characters

export class BitmapFont {
  // Draw a single character
  static drawChar(
    graphics: PIXI.Graphics,
    char: string,
    x: number,
    y: number,
    color: number
  ): number {
    const charData = FONT_DATA[char.toUpperCase()] || FONT_DATA[' '];

    for (let row = 0; row < CHAR_HEIGHT; row++) {
      const bits = charData[row];
      for (let col = 0; col < 3; col++) {
        if (bits & (1 << (2 - col))) {
          graphics.beginFill(color);
          graphics.drawRect(snap(x + col), snap(y + row), 1, 1);
          graphics.endFill();
        }
      }
    }

    return CHAR_WIDTH + CHAR_SPACING;
  }

  // Draw text string
  static drawText(
    graphics: PIXI.Graphics,
    text: string,
    x: number,
    y: number,
    color: number,
    scale: number = 1
  ): void {
    let offsetX = 0;

    for (let i = 0; i < text.length; i++) {
      const char = text[i];
      const charWidth = this.drawChar(graphics, char, x + offsetX, y, color);
      offsetX += charWidth * scale;
    }
  }

  // Measure text width
  static measureText(text: string, scale: number = 1): number {
    return text.length * (CHAR_WIDTH + CHAR_SPACING) * scale;
  }

  // Draw text with shadow (for emphasis)
  static drawTextWithShadow(
    graphics: PIXI.Graphics,
    text: string,
    x: number,
    y: number,
    color: number,
    shadowColor: number = 0x0f1317,
    scale: number = 1
  ): void {
    // Draw shadow (offset by 1 pixel)
    this.drawText(graphics, text, x + 1, y + 1, shadowColor, scale);
    // Draw main text
    this.drawText(graphics, text, x, y, color, scale);
  }

  // Draw large text (2x scale)
  static drawLargeText(
    graphics: PIXI.Graphics,
    text: string,
    x: number,
    y: number,
    color: number
  ): void {
    let offsetX = 0;

    for (let i = 0; i < text.length; i++) {
      const char = text[i];
      const charData = FONT_DATA[char.toUpperCase()] || FONT_DATA[' '];

      for (let row = 0; row < CHAR_HEIGHT; row++) {
        const bits = charData[row];
        for (let col = 0; col < 3; col++) {
          if (bits & (1 << (2 - col))) {
            graphics.beginFill(color);
            graphics.drawRect(
              snap(x + offsetX + col * 2),
              snap(y + row * 2),
              2,
              2
            );
            graphics.endFill();
          }
        }
      }

      offsetX += (CHAR_WIDTH + CHAR_SPACING) * 2;
    }
  }

  // Draw giant text (3x scale for stage total)
  static drawGiantText(
    graphics: PIXI.Graphics,
    text: string,
    x: number,
    y: number,
    color: number,
    highlightColor?: number
  ): void {
    let offsetX = 0;

    for (let i = 0; i < text.length; i++) {
      const char = text[i];
      const charData = FONT_DATA[char.toUpperCase()] || FONT_DATA[' '];

      for (let row = 0; row < CHAR_HEIGHT; row++) {
        const bits = charData[row];
        for (let col = 0; col < 3; col++) {
          if (bits & (1 << (2 - col))) {
            // Main pixel
            graphics.beginFill(color);
            graphics.drawRect(
              snap(x + offsetX + col * 3),
              snap(y + row * 3),
              3,
              3
            );
            graphics.endFill();

            // Inner highlight (1px)
            if (highlightColor) {
              graphics.beginFill(highlightColor);
              graphics.drawRect(
                snap(x + offsetX + col * 3 + 1),
                snap(y + row * 3 + 1),
                1,
                1
              );
              graphics.endFill();
            }
          }
        }
      }

      offsetX += (CHAR_WIDTH + CHAR_SPACING) * 3;
    }
  }
}
